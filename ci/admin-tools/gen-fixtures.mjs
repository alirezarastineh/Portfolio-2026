// Pulls the admin spec's fake API out of client/e2e/admin.spec.ts (Playwright forbids importing a
// spec from a spec, and a plain script cannot import it either) into fixtures.generated.mjs, fed
// with the realistic e2e content rather than the placeholder fallback.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const CLIENT = fileURLToPath(new URL("../../client", import.meta.url)).replace(/[\\/]$/, "");
const ts = createRequire(`${CLIENT}/package.json`)("typescript");
const src = readFileSync(`${CLIENT}/e2e/admin.spec.ts`, "utf8");
const end = src.indexOf('test.describe("admin", () => {');
if (end < 0) {
  throw new Error("spec layout changed");
}
let head = src
  .slice(0, end)
  .split("\n")
  .filter((l) => !l.startsWith('import '))
  .join("\n");
// Realistic content in place of the fallback JSON.
head = head.replace(
  /const content = \(locale: "en" \| "de"\) =>[\s\S]*?as Record<string, unknown>;/,
  'const content = (locale: "en" | "de") => fixtureCore(locale) as Record<string, unknown>;',
);
if (!head.includes("fixtureCore(locale)")) {
  throw new Error("content() not replaced");
}
const js = ts.transpileModule(head, {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
}).outputText;
const out = `// GENERATED by gen-fixtures.mjs from client/e2e/admin.spec.ts. Do not edit.
import { fixtureCore, fixtureDocs } from "${pathToFileURL(`${CLIENT}/e2e/fixture-content.mjs`).href}";
const interactive = async (page) => { await page.locator("html[data-hydrated]").waitFor({ state: "attached" }); };
${js}
export { defaults, fakeApi, openAdmin, content, fixtureDocs, USER, PIXEL, NOW, HOUR_AGO, message, projectRow, postRow, mediaAsset, outcomesView, perceptionView, skillVersion, copilotSkillsView, routerView, noVerdicts, answerRow, journalEntry, lessonRow, assistantSettings, trustView, ASSISTANT_ENV, JOURNAL_ID, LESSON_ID };
`;
writeFileSync(new URL("./fixtures.generated.mjs", import.meta.url), out);
console.log("wrote fixtures.generated.mjs", out.length, "bytes");
